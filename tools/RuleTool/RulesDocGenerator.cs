using System.Globalization;
using System.Text;
using Riegel.Core.Model;
using Riegel.Core.Resources;

namespace Riegel.Tools.RuleTool;

/// <summary>
/// Erzeugt docs/rules.md aus allen vorhandenen Regeldateien: je Berichtskategorie eine Tabelle mit ID, Titel en/de,
/// Schwere, Art, Verweisen und Belegquellen. Die Ausgabe ist deterministisch (keine Zeitstempel, feste Reihenfolge,
/// LF-Zeilenenden), damit ein zweiter Lauf dieselben Bytes liefert.
/// </summary>
public static class RulesDocGenerator
{
    /// <summary>Markdown für das Repository <paramref name="repo"/>.</summary>
    public static string Generate(RuleRepository repo)
    {
        var rules = repo.Rules.ToList();
        var byCategory = RuleCategories.All
            .Select(c => (Category: c, Rules: rules.Where(r => r.Category == c).OrderBy(r => r.Id, RuleIdComparer.Instance).ToList()))
            .Where(c => c.Rules.Count > 0)
            .ToList();
        var unknown = rules.Where(r => !RuleCategories.IsKnown(r.Category)).OrderBy(r => r.Id, RuleIdComparer.Instance).ToList();

        var sb = new StringBuilder();
        sb.Append("[Riegel](../README.md) › Rule catalogue\n\n");
        sb.Append("# Rule catalogue\n\n");
        var contents = new List<string> { "[Overview](#overview)" };
        contents.AddRange(byCategory.Select(c => $"[{CategoryName(c.Category)}](#{Anchor(CategoryName(c.Category))})"));
        contents.Add("[Sources and licences](#sources-and-licences)");
        sb.Append("**Contents:** ").Append(string.Join(" · ", contents)).Append("\n\n");
        sb.Append("This page is generated by `RuleTool rules-doc` from the rule files under [`rules/`](../rules/). Do not edit it\n");
        sb.Append("by hand: change the rule files and run the tool again; a test checks that the page is current.\n\n");

        sb.Append("## Overview\n\n");
        var checks = rules.Count(r => r.Kind == RuleKind.Check && r.State == RuleState.Active);
        var inventory = rules.Count(r => r.Kind == RuleKind.Inventory && r.State == RuleState.Active);
        var retired = rules.Count(r => r.State == RuleState.Retired);
        sb.Append(CultureInfo.InvariantCulture,
            $"Catalogue `{repo.Header.Id}` version {repo.Header.Version}, released {repo.Header.ReleasedOn:yyyy-MM-dd}. ");
        sb.Append(CultureInfo.InvariantCulture,
            $"The files present hold {rules.Count} rules: {checks} checks, {inventory} inventory rules and {retired} retired rules ");
        sb.Append(CultureInfo.InvariantCulture, $"in {repo.Files.Count} files ({string.Join(", ", repo.Files.Select(f => "`" + Path.GetFileName(f.File) + "`"))}).\n\n");
        sb.Append("| Category | Rules | Checks | Inventory | High | Medium | Low |\n|---|---|---|---|---|---|---|\n");
        foreach (var (category, list) in byCategory)
        {
            var active = list.Where(r => r.State == RuleState.Active).ToList();
            sb.Append(CultureInfo.InvariantCulture,
                $"| {CategoryName(category)} | {active.Count} | {active.Count(r => r.Kind == RuleKind.Check)} | {active.Count(r => r.Kind == RuleKind.Inventory)} | " +
                $"{active.Count(r => r.Severity == Severity.High)} | {active.Count(r => r.Severity == Severity.Medium)} | {active.Count(r => r.Severity == Severity.Low)} |\n");
        }
        sb.Append('\n');
        sb.Append("Severity is Riegel's own scale (high, medium, low). *Check* rules compare a value with an expected value and give\n");
        sb.Append("pass, fail or not checkable; *inventory* rules only list facts. The column *Sources* names the sources that back the\n");
        sb.Append("expected value (`verified` in the rule file); the column *References* lists cross-references. Microsoft Security\n");
        sb.Append("Baseline references name the document and the setting only, never a value.\n\n");

        foreach (var (category, list) in byCategory)
            AppendTable(sb, CategoryName(category), list);
        if (unknown.Count > 0)
            AppendTable(sb, "Unknown category", unknown);

        sb.Append("## Sources and licences\n\n");
        sb.Append("Rule texts are Riegel's own. The sources, their licences and the attribution lines are listed in\n");
        sb.Append("[rule sources](rule-sources.md); the framework mapping and its disclaimers are in [frameworks](frameworks.md).\n");
        sb.Append("Abbreviations: ACSC = Australian Cyber Security Centre, *Hardening Microsoft Windows 11 workstations*; DISA = STIG IDs;\n");
        sb.Append("GS++ = BSI Grundschutz++ identifiers; ATT&CK = MITRE ATT&CK mitigation IDs; MSB = Microsoft Security Baseline;\n");
        sb.Append("MSDOCS-CCBY = Microsoft Windows Server documentation (CC BY 4.0); MSLEARN-FACT = facts from Microsoft Learn.\n");
        return sb.ToString();
    }

    private static void AppendTable(StringBuilder sb, string heading, IReadOnlyList<Rule> rules)
    {
        sb.Append("## ").Append(heading).Append("\n\n");
        sb.Append("| ID | Title | Titel (de) | Severity | Kind | References | Sources |\n|---|---|---|---|---|---|---|\n");
        foreach (var r in rules)
        {
            var id = r.State == RuleState.Retired ? r.Id + " (retired)" : r.Id;
            var sources = r.Verified.Select(v => v.Src).Distinct(StringComparer.Ordinal).ToList();
            if (r.TextSources.Count > 0) sources.Add("text adapted: " + string.Join(", ", r.TextSources.Select(t => t.Src).Distinct(StringComparer.Ordinal)));
            sb.Append("| ").Append(Cell(id))
              .Append(" | ").Append(Cell(r.Title.Get("en")))
              .Append(" | ").Append(Cell(r.Title.Get("de")))
              .Append(" | ").Append(r.Severity.ToString().ToLowerInvariant())
              .Append(" | ").Append(r.Kind.ToString().ToLowerInvariant())
              .Append(" | ").Append(References(r))
              .Append(" | ").Append(sources.Count == 0 ? "–" : Cell(string.Join(", ", sources)))
              .Append(" |\n");
        }
        sb.Append('\n');
    }

    /// <summary>Verweise einer Regel, je Quelle zusammengefasst, getrennt durch &lt;br&gt;.</summary>
    public static string References(Rule rule)
    {
        var parts = new List<string>();
        foreach (var group in rule.References.GroupBy(r => r.Src, StringComparer.Ordinal))
        {
            var refs = group.ToList();
            switch (group.Key)
            {
                case "ACSC":
                    parts.Add("ACSC: " + string.Join("; ", refs.Select(r => r.Section ?? r.Doc ?? "").Where(s => s.Length > 0)));
                    break;
                case "MSB":
                    parts.Add("MSB: " + string.Join("; ", refs.Select(r => r.Setting ?? "").Where(s => s.Length > 0)));
                    break;
                case "DISA":
                    parts.Add("DISA: " + string.Join(", ", refs.Select(r => r.Id ?? r.Section ?? "").Where(s => s.Length > 0)));
                    break;
                case "GSPP":
                    parts.Add("GS++: " + string.Join(", ", refs.SelectMany(r => (r.Ids ?? []).Concat(r.Id is null ? [] : [r.Id]))));
                    break;
                case "ATTACK":
                    parts.Add("ATT&CK: " + string.Join(", ", refs.SelectMany(r => (r.Ids ?? []).Concat(r.Id is null ? [] : [r.Id]))));
                    break;
                case "ENDOFLIFE":
                    parts.Add("endoflife.date");
                    break;
                default:
                    parts.Add(group.Key + ": " + string.Join("; ", refs.Select(r => r.Doc ?? r.Setting ?? r.Id ?? r.Url ?? "").Where(s => s.Length > 0)));
                    break;
            }
        }
        return parts.Count == 0 ? "–" : string.Join("<br>", parts.Select(Cell));
    }

    /// <summary>Englischer Anzeigename einer Kategorie (CommonStrings, unabhängig von der Sprache des Systems).</summary>
    public static string CategoryName(string category) =>
        CommonStrings.ResourceManager.GetString("Category_" + category, CultureInfo.InvariantCulture) ?? category;

    /// <summary>Anker wie GitHub ihn aus einer Überschrift bildet.</summary>
    public static string Anchor(string heading)
    {
        var sb = new StringBuilder();
        foreach (var ch in heading.ToLowerInvariant())
        {
            if (char.IsLetterOrDigit(ch) || ch == '-' || ch == '_') sb.Append(ch);
            else if (ch == ' ') sb.Append('-');
        }
        return sb.ToString();
    }

    private static string Cell(string text) => text.Replace("|", "\\|", StringComparison.Ordinal).Replace("\r", "", StringComparison.Ordinal).Replace("\n", " ", StringComparison.Ordinal);
}

/// <summary>Sortiert Regel-IDs nach Präfix und Nummer (NET-2 vor NET-10).</summary>
public sealed class RuleIdComparer : IComparer<string>
{
    public static RuleIdComparer Instance { get; } = new();

    public int Compare(string? x, string? y)
    {
        if (ReferenceEquals(x, y)) return 0;
        if (x is null) return -1;
        if (y is null) return 1;
        var (px, nx) = Split(x);
        var (py, ny) = Split(y);
        var c = string.CompareOrdinal(px, py);
        if (c != 0) return c;
        c = nx.CompareTo(ny);
        return c != 0 ? c : string.CompareOrdinal(x, y);
    }

    private static (string Prefix, int Number) Split(string id)
    {
        var dash = id.LastIndexOf('-');
        return dash > 0 && int.TryParse(id[(dash + 1)..], NumberStyles.None, CultureInfo.InvariantCulture, out var n) ? (id[..dash], n) : (id, 0);
    }
}
